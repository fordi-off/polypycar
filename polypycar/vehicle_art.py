def arch(cx, w, h, bottom):
    """Trapezoid-ish wheel arch centred at cx."""
    return [(cx - w, bottom), (cx - w + 0.05, bottom + h * 0.2), (cx - w * 0.65, bottom + h * 0.7), (cx - w * 0.25, bottom + h),
            (cx + w * 0.25, bottom + h), (cx + w * 0.65, bottom + h * 0.7), (cx + w - 0.05, bottom + h * 0.2), (cx + w, bottom)]


def _flares(c, mounts, w, h, bottom, width=0.09):
    for cx in mounts:
        pts = c.L([(x, y + 0.03) for x, y in arch(cx, w, h, bottom)[1:-1]])
        c.paint.lines(rgb(DARK), pts, max(2, int(c.view.s * width)))


def _driver(c, hx, hy, scale, cap=(210, 60, 52), shirt=(58, 68, 94)):
    poly = c.poly
    hx, hy = hx + c.head[0] * 1.5 * scale, hy + c.head[1] * 1.5 * scale
    r = 0.2 * scale
    poly(shirt, [(hx - 0.8 * scale, hy - 0.4 * scale), (hx - 0.65 * scale, hy - 0.15 * scale), (hx - r, hy - 0.15 * scale),
                 (hx + r, hy - 0.15 * scale), (hx + 0.7 * scale, hy - 0.4 * scale)])
    poly((238, 192, 152), [(hx + math.cos(a * math.tau / 8) * r, hy + math.sin(a * math.tau / 8) * r * 1.1) for a in range(8)])
    poly(cap, [(hx - r * 1.1, hy + r * 0.2), (hx + r * 1.1, hy + r * 0.2), (hx + r * 1.4, hy), (hx + r * 0.5, hy + r * 1.3), (hx - r * 0.5, hy + r * 1.25)])


